import React from "react";
import { act, create, type ReactTestRenderer } from "react-test-renderer";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ ask: vi.fn(), history: vi.fn(), clear: vi.fn(), sound: vi.fn() }));
vi.mock("@/actions/support", () => ({ askSupportAssistantAction: mocks.ask, getSupportHistoryAction: mocks.history, clearSupportHistoryAction: mocks.clear }));
vi.mock("./use-support-sound", () => ({ useSupportSound: () => ({ enabled: false, toggle: vi.fn(), prepare: vi.fn(), complete: mocks.sound }) }));
vi.mock("@/providers/i18n-provider", () => ({ useI18n: () => ({ locale: "en" }) }));
vi.mock("@/components/i18n/use-ui", () => ({ useUi: () => (s: string) => s }));
vi.mock("@/components/i18n/localized-copy", () => ({ UiText: ({ children }: { children: React.ReactNode }) => <>{children}</> }));
vi.mock("next/link", () => ({ default: ({ children }: { children: React.ReactNode }) => <a>{children}</a> }));
vi.mock("./support-resources", () => ({ SupportResources: () => null }));
vi.mock("./support-actions", () => ({ SupportActions: () => null }));
vi.mock("@radix-ui/react-dialog", () => { const Pass = ({ children }: { children: React.ReactNode }) => <>{children}</>; return { Root: Pass, Portal: Pass, Overlay: () => null, Content: Pass, Title: Pass, Description: Pass }; });
vi.mock("@/components/ui/popover", () => { const Pass = ({ children }: { children: React.ReactNode }) => <>{children}</>; return { Popover: Pass, PopoverTrigger: Pass, PopoverContent: Pass }; });
import HelpHub, { SupportAssistant } from "./help-hub";
let tree: ReactTestRenderer;
beforeEach(() => {
  vi.useFakeTimers(); vi.clearAllMocks();
  vi.stubGlobal("window", { matchMedia: () => ({ matches: false, addEventListener: vi.fn(), removeEventListener: vi.fn() }) });
  vi.stubGlobal("document", { hidden: false, addEventListener: vi.fn(), removeEventListener: vi.fn() });
  mocks.history.mockResolvedValue({ status: 200, messages: [] });
  mocks.ask.mockResolvedValue({ status: 200, userMessage: { id: "q", role: "user", content: "Which AP3K plan fits my needs?" }, assistantMessage: { id: "a", role: "assistant", content: "Tell me which features you need." } });
});
afterEach(() => { act(() => tree?.unmount()); vi.useRealTimers(); vi.unstubAllGlobals(); });
it("expands Help within the mobile drawer and opens the assistant", async () => {
  await act(async () => { tree = create(<HelpHub slug="owner" mobile />); });
  const help = () => tree.root.findAllByType("button").find(b => b.props["aria-label"] === "Help")!;
  expect(help().props["aria-expanded"]).toBe(false);
  act(() => help().props.onClick());
  expect(help().props["aria-expanded"]).toBe(true);
  expect(tree.root.findByProps({ id: help().props["aria-controls"] }).props.className).toContain("overflow-y-auto");
  const open = tree.root.findAllByType("button").find(b => b.findAllByType("span").some(s => s.children.some(c => typeof c !== "string" && c.type && c.props.children === "Get help")));
  expect(open).toBeDefined();
  await act(async () => { open!.props.onClick(); });
  expect(tree.root.findAllByType(SupportAssistant)).toHaveLength(1);
  expect(help().props["aria-expanded"]).toBe(false);
});
it("suggestions send immediately once, then reveal the reply after a short cue", async () => {
  await act(async () => { tree = create(<SupportAssistant workspace="owner" onClose={() => {}} onRestoreFocus={() => {}} />); });
  const suggestion = () => tree.root.findAllByType("button").find(b => b.props.className?.includes("text-start text-xs"))!;
  await act(async () => { suggestion().props.onClick(); suggestion().props.onClick(); });
  expect(mocks.ask).toHaveBeenCalledOnce();
  expect(mocks.ask).toHaveBeenCalledWith("Which AP3K plan fits my needs?");
  expect(suggestion().props.disabled).toBe(true);
  expect(JSON.stringify(tree.toJSON())).not.toContain("Tell me which features");
  await act(async () => { vi.advanceTimersByTime(1000); });
  await act(async () => { vi.advanceTimersByTime(1850); });
  expect(JSON.stringify(tree.toJSON())).toContain("Tell me which features you need.");
  expect(suggestion().props.disabled).toBe(false);
  expect(mocks.sound).toHaveBeenCalledOnce();
});
